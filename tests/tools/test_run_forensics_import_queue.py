def test_runner_can_read_writeback_and_update_manifest_results(tmp_path: Path) -> None:
    source_path = _write_zip(
        tmp_path / "Bat.gcode.3mf",
        {
            "Metadata/slice_info.config": "<slice-info />",
            "Metadata/plate_1.gcode": "; generated by Bambu Studio\n",
        },
    )
    manifest_path = _write_manifest(
        tmp_path / "manifest.json",
        {
            "gcode_name": "Bat_plate_1.gcode",
            "disposition": "Keep",
            "selected_source_path": str(source_path),
            "source_files": [
                {
                    "path": str(source_path),
                    "source_type": "bambu_studio_exported_sliced_3mf",
                    "canonical_archive_ready": True,
                    "suggested_import_mode": "create_archive_upload",
                    "modified_at": "2026-04-12T19:16:06Z",
                }
            ],
            "import_plan": {
                "mode": "create_archive_upload",
                "inferred_started_at": "2026-04-12T19:16:06Z",
                "inferred_created_at": "2026-04-12T19:16:06Z",
            },
        },
    )

    entries = read_manifest_triage_entries(manifest_path)
    assert len(entries) == 1
    item = assess_entry(entries[0])
    synthetic = build_synthetic_manifest([item], batch_id="forensics-test")
    synthetic_manifest_path = tmp_path / "synthetic.json"
    write_json(synthetic_manifest_path, synthetic)

    synthetic_entry = synthetic["candidates"][0]
    backfill_result = {
        "result": {
            "results": [
                {
                    "entry_id": synthetic_entry["entry_id"],
                    "status": "uploaded_and_annotated",
                    "reason": "Archive created from manifest candidate.",
                    "created_archive_id": 612,
                    "matched_archive_id": None,
                }
            ]
        },
        "result_path": str(tmp_path / "result.json"),
    }
    update_source_manifest(
        manifest_path,
        [item],
        synthetic_manifest_path=synthetic_manifest_path,
        backfill_result=backfill_result,
        repair_results={"Bat_plate_1.gcode": {"applied": True}},
    )

    updated = load_json(manifest_path)
    runner = updated["secondary_artifact_analysis"]["cache_secondary_artifacts"]["manual_triage_decisions"]["entries"][0]["import_runner"]
    assert runner["queue_status"] == "ready"
    assert runner["created_archive_id"] == 612
    assert runner["runtime_repair"]["applied"] is True

    summary = queue_summary([item])
    assert summary["counts"]["ready"] == 1


