def test_upload_source_attachment_posts_to_archive_source_endpoint(tmp_path: Path, monkeypatch) -> None:
    source_path = _write_zip(tmp_path / "Source.3mf", {"3D/Objects/object_1.model": "<model />"})
    captured: dict[str, object] = {}

    class DummyResponse:
        def __enter__(self):
            return self

        def __exit__(self, exc_type, exc, tb):
            return False

        def read(self):
            return json.dumps({"status": "uploaded", "source_3mf_path": "archive/1/source/Source.3mf", "filename": "Source.3mf"}).encode("utf-8")

    def fake_urlopen(request: Request):
        captured["url"] = request.full_url
        captured["content_type"] = request.headers.get("Content-type") or request.headers.get("Content-Type")
        captured["api_key"] = request.headers.get("X-api-key") or request.headers.get("X-API-Key")
        captured["body"] = request.data
        return DummyResponse()

    monkeypatch.setattr("urllib.request.urlopen", fake_urlopen)

    result = upload_source_attachment(170, source_path, base_url="http://bambuddy.socko.us", api_key="secret")

    assert captured["url"] == "http://bambuddy.socko.us/api/v1/archives/170/source"
    assert "multipart/form-data" in str(captured["content_type"])
    assert captured["api_key"] == "secret"
    assert b"Source.3mf" in bytes(captured["body"])
    assert result["status"] == "uploaded"


def test_runner_dry_run_generates_path2_artifact_and_attachment_preview(tmp_path: Path, monkeypatch, capsys) -> None:
    raw_gcode_path = tmp_path / "Recovered_plate_1.gcode"
    raw_gcode_path.write_text(
        "; generated by Bambu Studio\n; estimated printing time = 1h 10m\n; filament_ids = 1;2\nG1 X1 Y1 E1\n",
        encoding="utf-8",
    )
    source_project = _write_zip(tmp_path / "Source.3mf", {"3D/Objects/object_1.model": "<model />"})
    reference = _write_zip(
        tmp_path / "KnownGood.gcode.3mf",
        {
            "Metadata/slice_info.config": "<slice-info />",
            "Metadata/project_settings.config": "{}",
            "Metadata/plate_1.gcode": "; generated by Bambu Studio\n",
            "Metadata/plate_1.png": b"png-bytes",
        },
    )
    manifest_path = _write_manifest(
        tmp_path / "manifest.json",
        {
            "gcode_name": "Recovered_plate_1.gcode",
            "disposition": "Keep",
            "archive_id": 170,
            "selected_source_path": str(raw_gcode_path),
            "source_files": [
                {
                    "path": str(raw_gcode_path),
                    "source_type": "raw_gcode_file",
                    "canonical_archive_ready": False,
                    "suggested_import_mode": "wrap_raw_gcode_experimental",
                    "modified_at": "2026-04-11T19:16:06Z",
                    "header_metadata": {"filament_slots": "1;2", "print_time": "1h 10m"},
                },
                {
                    "path": str(source_project),
                    "source_type": "bambu_studio_source_3mf",
                    "canonical_archive_ready": False,
                    "suggested_import_mode": "attach_source_only",
                    "modified_at": "2026-04-11T19:16:06Z",
                },
            ],
            "import_plan": {
                "mode": "wrap_raw_gcode_experimental",
                "inferred_started_at": "2026-04-11T19:16:06Z",
            },
        },
    )
    manifest = load_json(manifest_path)
    manifest["secondary_artifact_analysis"]["cache_secondary_artifacts"]["manual_triage_decisions"]["entries"].append(
        {
            "gcode_name": "Source_plate_1.gcode",
            "disposition": "Keep",
            "archive_id": 171,
            "selected_source_path": str(source_project),
            "source_files": [
                {
                    "path": str(source_project),
                    "source_type": "bambu_studio_source_3mf",
                    "canonical_archive_ready": False,
                    "suggested_import_mode": "attach_source_only",
                    "modified_at": "2026-04-12T19:16:06Z",
                }
            ],
            "import_plan": {
                "mode": "attach_source_only",
                "inferred_started_at": "2026-04-12T19:16:06Z",
            },
        }
    )
    write_json(manifest_path, manifest)
    dry_run_dir = tmp_path / "dry-run"
    monkeypatch.setattr(
        "sys.argv",
        [
            "run_forensics_import_queue.py",
            "--manifest",
            str(manifest_path),
            "--action",
            "dry-run",
            "--dry-run-output-dir",
            str(dry_run_dir),
            "--compare-to",
            str(reference),
        ],
    )

    result = runner_main()
    payload = json.loads(capsys.readouterr().out)

    assert result == 0
    assert payload["dry_run"]["source_attachments"]["Source_plate_1.gcode"]["would_call"].endswith("/171/source")
    artifact = payload["dry_run"]["path2_artifacts"]["Recovered_plate_1.gcode"]
    assert Path(artifact["output_path"]).exists()
    assert artifact["report"]["comparisons"][0]["reference_path"] == str(reference)